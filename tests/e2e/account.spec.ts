import { expect, test } from '@playwright/test'

async function signIn(page: import('@playwright/test').Page, email = 'luna@demo.kurio', password = 'Luna@Kurio2026!') {
  await page.goto('/login')
  await page.getByLabel('E-mail').fill(email)
  await page.getByLabel('Senha').fill(password)
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('link', { name: /Luna Alves|Rafael Costa/ })).toBeVisible()
}

test('edita e recupera o perfil depois de atualizar a página', async ({ page }) => {
  await signIn(page)
  await page.goto('/profile')
  await page.getByLabel('Nome de exibição').fill('Luna Colecionadora')
  await page.getByLabel('Nome de usuário').fill('luna_coleciona')
  await page.getByLabel('Nome ENS').fill('luna.eth')
  await page.getByLabel('Apelido da carteira').fill('Minha Vault')
  await page.getByRole('button', { name: 'Salvar perfil' }).click()
  await expect(page.getByRole('status')).toContainText('Perfil salvo com sucesso')
  await page.reload()
  await expect(page.getByLabel('Nome de exibição')).toHaveValue('Luna Colecionadora')
  await expect(page.getByLabel('Nome ENS')).toHaveValue('luna.eth')
})

