test('sincroniza favoritos entre catálogo e detalhes e recupera após refresh', async ({ page }) => {
  await signIn(page)
  await page.goto('/nft/nft-001')
  await expect(page.getByRole('heading', { name: 'Crimson Ember' })).toBeVisible()
  await page.getByRole('button', { name: 'Adicionar Crimson Ember aos favoritos' }).click()
  await expect(page.getByRole('button', { name: 'Remover Crimson Ember dos favoritos' })).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/')
  const card = page.getByTestId('nft-card').filter({ has: page.getByRole('heading', { name: 'Crimson Ember' }) })
  await expect(card.getByRole('button', { name: 'Remover Crimson Ember dos favoritos' })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  const refreshedCard = page.getByTestId('nft-card').filter({ has: page.getByRole('heading', { name: 'Crimson Ember' }) })
  await refreshedCard.getByRole('button', { name: 'Remover Crimson Ember dos favoritos' }).click()
  await expect(refreshedCard.getByRole('button', { name: 'Adicionar Crimson Ember aos favoritos' })).toHaveAttribute('aria-pressed', 'false')
  await page.goto('/nft/nft-001')
  await expect(page.getByRole('heading', { name: 'Crimson Ember' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Adicionar Crimson Ember aos favoritos' })).toHaveAttribute('aria-pressed', 'false')
})

